// Local development server for map.html (Node 18+, no dependencies).
//
//   node dev-server.mjs
//   open http://localhost:3001/
//
// The browser loads this page, its CSS/JS, and CDTA JSONs from the same origin.
// Requests to /api/* are still proxied to the Shubble backend.

import http from 'node:http';
import https from 'node:https';
import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const PORT = Number(process.env.PORT ?? 3001);
const UPSTREAM = new URL(process.env.UPSTREAM ?? 'https://shuttles.rpi.edu');
const DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const client = UPSTREAM.protocol === 'https:' ? https : http;

// ---------------------------------------------------------------
// Optional Tiger Data endpoints. When TIGER_DATABASE_URL is set (run
// `node --env-file=.env dev-server.mjs`), /api/db/* reads live analytics
// from Postgres. Without it those endpoints report 503 and the map keeps
// working purely from local JSON.
// ---------------------------------------------------------------
let dbPool = null;
if (process.env.TIGER_DATABASE_URL) {
    try {
        const {default: pg} = await import('pg');
        dbPool = new pg.Pool({connectionString: process.env.TIGER_DATABASE_URL, max: 3});
        console.log('Tiger Data: /api/db/* endpoints enabled');
    } catch (err) {
        console.log(`Tiger Data: pg not installed (${err.message}); /api/db/* disabled`);
    }
}

// GET /api/db/shuttle-travel-times -> median minutes between stop pairs by hour
async function dbShuttleTravelTimes(res) {
    const {rows} = await dbPool.query(
        `SELECT route_key, from_stop, to_stop, hour_of_day, samples, median_min
         FROM shuttle_travel_times
         ORDER BY route_key, from_stop, to_stop, hour_of_day`
    );
    res.writeHead(200, {'content-type': 'application/json; charset=utf-8'});
    res.end(JSON.stringify({source: 'tigerdata', travelTimes: rows}));
}

// GET /api/db/shuttle-activity?hours=2 -> pings per minute per route (recency sparkline)
async function dbShuttleActivity(res, url) {
    const hours = Math.min(24, Math.max(1, Number(url.searchParams.get('hours') ?? 2)));
    const {rows} = await dbPool.query(
        `SELECT time_bucket('1 minute', recorded_at) AS minute,
                route_key, COUNT(DISTINCT vehicle_id) AS vehicles
         FROM shuttle_positions
         WHERE recorded_at > now() - ($1 || ' hours')::interval
         GROUP BY minute, route_key
         ORDER BY minute`,
        [String(hours)]
    );
    res.writeHead(200, {'content-type': 'application/json; charset=utf-8'});
    res.end(JSON.stringify({source: 'tigerdata', activity: rows}));
}

// Only these static files are served. No arbitrary filesystem paths are exposed.
const staticContentTypes = new Map([
    ['/map.html', 'text/html; charset=utf-8'],
    ['/map.css', 'text/css; charset=utf-8'],
    ['/map.js', 'text/javascript; charset=utf-8'],
    ['/cdta-transit.json', 'application/json; charset=utf-8'],
    ['/cdta-departures.json', 'application/json; charset=utf-8'],
    // Trip planner bundle (generated by planner/build-planner-data.mjs) and
    // its ES modules.
    ['/planner/planner-data.json', 'application/json; charset=utf-8'],
    ['/js/journey.js', 'text/javascript; charset=utf-8'],
    ['/js/journey-ui.js', 'text/javascript; charset=utf-8'],
    ['/js/time.js', 'text/javascript; charset=utf-8'],
    ['/bikedata.geojson', 'application/geo+json; charset=utf-8']
]);

const server = http.createServer(async (req, res) => {
    const {pathname} = new URL(req.url, 'http://local');

    // Tiger Data read endpoints (only active when the pool exists).
    if (pathname.startsWith('/api/db/') && !dbPool) {
        res.writeHead(503, {'content-type': 'application/json; charset=utf-8'});
        res.end(JSON.stringify({error: 'Tiger Data not configured (set TIGER_DATABASE_URL)'}));
        return;
    }
    if (dbPool && pathname === '/api/db/shuttle-travel-times') {
        try {
            await dbShuttleTravelTimes(res);
        } catch (err) {
            res.writeHead(500, {'content-type': 'application/json; charset=utf-8'});
            res.end(JSON.stringify({error: err.message}));
        }
        return;
    }
    if (dbPool && pathname === '/api/db/shuttle-activity') {
        try {
            await dbShuttleActivity(res, new URL(req.url, 'http://local'));
        } catch (err) {
            res.writeHead(500, {'content-type': 'application/json; charset=utf-8'});
            res.end(JSON.stringify({error: err.message}));
        }
        return;
    }

    if (pathname.startsWith('/api/')) {
        const upstreamReq = client.request({
            hostname: UPSTREAM.hostname,
            port: UPSTREAM.port || undefined,
            path: req.url,
            method: req.method,
            headers: {...req.headers, host: UPSTREAM.host}
        }, upstreamRes => {
            res.writeHead(upstreamRes.statusCode, upstreamRes.headers);
            upstreamRes.pipe(res);
        });
        upstreamReq.on('error', err => {
            if (!res.headersSent) {
                res.writeHead(502, {'content-type': 'text/plain; charset=utf-8'});
            }
            res.end(`Could not reach ${UPSTREAM.origin}: ${err.message}`);
        });
        req.pipe(upstreamReq);
        return;
    }

    const filename = pathname === '/' ? '/map.html' : pathname;
    const contentType = staticContentTypes.get(filename);
    if (contentType) {
        try {
            const bytes = await readFile(path.join(DIRECTORY, filename.slice(1)));
            res.writeHead(200, {'content-type': contentType});
            res.end(bytes);
        } catch (err) {
            res.writeHead(err.code === 'ENOENT' ? 404 : 500, {
                'content-type': 'text/plain; charset=utf-8'
            });
            res.end(`Could not read ${filename}: ${err.message}`);
        }
        return;
    }

    res.writeHead(pathname === '/favicon.ico' ? 204 : 404);
    res.end();
});

server.listen(PORT, () => {
    console.log(`Map:      http://localhost:${PORT}/`);
    console.log(`Proxying: /api/* -> ${UPSTREAM.origin}`);
    if (!dbPool) console.log('Tiger:    /api/db/* disabled (no TIGER_DATABASE_URL)');
});
